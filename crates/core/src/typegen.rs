fn export_all<T: TS + 'static>(config: &Config) -> Result<(), AppError> {
    T::export_all(config).map_err(|error| {
        AppError::new(
            ErrorCode::Io,
            format!("unable to generate TypeScript bindings: {error}"),
        )
    })
}

fn generated_dir(path: &Path) -> Result<PathBuf, AppError> {
    path.parent()
        .map(|parent| parent.join("generated"))
        .ok_or_else(|| AppError::invalid_argument("generated binding path must have a parent"))
}

fn prepare_generated_dir(path: &Path) -> Result<(), AppError> {
    fs::create_dir_all(path)?;
    for entry in fs::read_dir(path)? {
        let entry = entry?;
        if entry
            .path()
            .extension()
            .is_some_and(|extension| extension == "ts")
        {
            fs::remove_file(entry.path())?;
        }
    }
    Ok(())
}

